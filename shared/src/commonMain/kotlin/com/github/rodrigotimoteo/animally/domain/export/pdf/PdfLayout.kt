package com.github.rodrigotimoteo.animally.domain.export.pdf

/**
 * A single drawing instruction of the platform-neutral PDF layout model.
 *
 * Rectangles use a top-left origin; text [PdfOp.Text.y] is the top of the
 * text box. Platform painters translate these to their native APIs.
 */
internal sealed interface PdfOp {
    /**
     * Fills a rectangle.
     *
     * @property color ARGB fill color from [PdfTheme].
     */
    data class Rect(
        val x: Double,
        val y: Double,
        val width: Double,
        val height: Double,
        val color: Long,
    ) : PdfOp

    /**
     * Draws one line of text.
     *
     * @property y top edge of the text box.
     * @property rightAligned when set, [x] is the right edge.
     * @property centered when set, [x] is the center.
     */
    data class Text(
        val text: String,
        val x: Double,
        val y: Double,
        val size: Double,
        val bold: Boolean,
        val color: Long,
        val rightAligned: Boolean = false,
        val centered: Boolean = false,
    ) : PdfOp
}

/** One laid-out page of the report, with its footer metadata resolved. */
internal data class PdfPageModel(
    val pageNumber: Int,
    val totalPages: Int,
    val ops: List<PdfOp>,
)

/**
 * Builds the full page models for [report]: branded header band on every
 * page, demographics grid, one aligned table per non-empty section, and a
 * "Page X of Y" footer. Both platform renderers paint these ops verbatim,
 * which keeps the documents visually identical.
 */
internal fun layoutReport(report: PdfReportData): List<PdfPageModel> {
    val generatedAt = generationStamp()
    val contentOps = paginate(report)
    val totalPages = contentOps.size
    return contentOps.mapIndexed { index, ops ->
        val pageOps =
            buildList {
                addAll(headerBandOps(generatedAt))
                addAll(ops)
                addAll(footerOps(index + 1, totalPages, generatedAt))
            }
        PdfPageModel(
            pageNumber = index + 1,
            totalPages = totalPages,
            ops = pageOps,
        )
    }
}

// -------------------------------------------------------------------------
// Header band + footer
// -------------------------------------------------------------------------

private fun headerBandOps(generatedAt: String): List<PdfOp> =
    listOf(
        PdfOp.Rect(
            x = PdfTheme.MARGIN,
            y = PdfTheme.MARGIN,
            width = PdfTheme.CONTENT_WIDTH,
            height = PdfTheme.HEADER_BAND_HEIGHT,
            color = PdfTheme.COLOR_BRAND,
        ),
        PdfOp.Text(
            "Animally",
            PdfTheme.MARGIN + PdfTheme.BAND_PAD_H,
            PdfTheme.MARGIN + PdfTheme.BRAND_TEXT_OFFSET_Y,
            PdfTheme.BRAND_SIZE,
            true,
            PdfTheme.COLOR_WHITE,
        ),
        PdfOp.Text(
            "Patient History Report",
            PdfTheme.MARGIN + PdfTheme.BAND_PAD_H,
            PdfTheme.MARGIN + PdfTheme.BAND_TITLE_OFFSET_Y,
            PdfTheme.BAND_TITLE_SIZE,
            false,
            PdfTheme.COLOR_WHITE,
        ),
        PdfOp.Text(
            generatedAt,
            PdfTheme.MARGIN + PdfTheme.CONTENT_WIDTH - PdfTheme.BAND_PAD_H,
            PdfTheme.MARGIN + PdfTheme.BAND_DATE_OFFSET_Y,
            PdfTheme.BAND_DATE_SIZE,
            false,
            PdfTheme.COLOR_WHITE,
            rightAligned = true,
        ),
    )

private fun footerOps(
    pageNumber: Int,
    totalPages: Int,
    generatedAt: String,
): List<PdfOp> =
    listOf(
        PdfOp.Text(
            "Page $pageNumber of $totalPages",
            PdfTheme.PAGE_WIDTH / 2,
            PdfTheme.FOOTER_PAGE_LINE_Y,
            PdfTheme.FOOTER_SIZE,
            false,
            PdfTheme.COLOR_FOOTER,
            centered = true,
        ),
        PdfOp.Text(
            "Generated by Animally • $generatedAt",
            PdfTheme.PAGE_WIDTH / 2,
            PdfTheme.FOOTER_STAMP_LINE_Y,
            PdfTheme.FOOTER_SIZE,
            false,
            PdfTheme.COLOR_FOOTER,
            centered = true,
        ),
    )

